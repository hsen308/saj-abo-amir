/* Turn data/menu.csv into data/menu-sheet.json, ready to paste into
   Apps Script. Run: node tools/build-sheet-payload.js                   */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const csv = fs.readFileSync(path.join(ROOT, 'data', 'menu.csv'), 'utf8');

function parseCSV(text) {
  const rows = [];
  let row = [], field = '', inQ = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQ) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else inQ = false; }
      else field += c;
    } else if (c === '"') inQ = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows.filter(r => r.length && r.some(c => c.trim() !== ''));
}

const rows = parseCSV(csv);
const head = rows.shift();

// Two arrays of plain values: safe to paste into Apps Script, no quoting to survive.
const values = rows.map(r => head.map((_, i) => (r[i] === undefined ? '' : r[i])));

const payload = { header: head, rows: values };

const out = path.join(ROOT, 'tools', 'menu-payload.js');
fs.writeFileSync(out,
  '/* GENERATED by tools/build-sheet-payload.js. Do not edit by hand.\n' +
  '   Open the Google Sheet, then Extensions > Apps Script, and paste the\n' +
  '   two constants below into the editor to load the current menu. */\n' +
  'var MENU_HEADER = ' + JSON.stringify(payload.header) + ';\n' +
  'var MENU_ROWS = ' + JSON.stringify(payload.rows) + ';\n',
  'utf8');

console.log('wrote tools/menu-payload.js:', payload.rows.length, 'rows');
console.log('size:', Math.round(fs.statSync(out).size / 1024), 'KB');